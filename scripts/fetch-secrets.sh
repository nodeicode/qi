#!/usr/bin/env bash
# fetch-secrets.sh — Reads credentials from SSM Parameter Store and writes
# /opt/trading/quant/.env for the trader service to source via EnvironmentFile=
#
# Runs as ExecStartPre under root (before the trader user starts).
# Requires the EC2 IAM role to have ssm:GetParametersByPath permission on
# /trading/{env}/*.
set -euo pipefail

# Ensure system binaries are on PATH (systemd uses a minimal PATH).
export PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin:$PATH"

DEPLOY_DIR="/opt/trading"
ENV_FILE="$DEPLOY_DIR/quant/.env"
ENVIRONMENT=$(cat "$DEPLOY_DIR/.environment")
SSM_PATH="/trading/$ENVIRONMENT"

echo "Fetching secrets from SSM: $SSM_PATH"

# Pull all parameters under /trading/{env}/ in one API call
PARAMS=$(aws ssm get-parameters-by-path \
    --path "$SSM_PATH" \
    --with-decryption \
    --query "Parameters[*].{Name:Name,Value:Value}" \
    --output json)

# Write out as KEY=VALUE pairs, stripping the path prefix.
# Exclude strategies_config — its JSON value is read directly by ConfigSync
# via ssm:GetParameter and is not suitable as a plain env var.
# /trading/staging/alpaca_paper_api_key  →  ALPACA_PAPER_API_KEY=<value>
echo "# Auto-generated by fetch-secrets.sh — do not edit manually" > "$ENV_FILE"
echo "$PARAMS" | jq -r '
  .[] | select(.Name | endswith("/strategies_config") | not)
  | .Name + "=" + .Value
' | while read -r LINE; do
    # Strip path prefix and upper-case the key portion
    KEY=$(echo "$LINE" | sed "s|$SSM_PATH/||" | cut -d= -f1 | tr '[:lower:]' '[:upper:]' | tr '-' '_')
    VALUE=$(echo "$LINE" | cut -d= -f2-)
    echo "$KEY=$VALUE"
done >> "$ENV_FILE"

chmod 600 "$ENV_FILE"
chown trader:trader "$ENV_FILE"


echo "Secrets written to $ENV_FILE"